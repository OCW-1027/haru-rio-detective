def align(surf, rd):
    segs=re.findall(r'[一-鿿々〆ヶ]+|[^一-鿿々〆ヶ]+', surf)
    pat='^'+''.join('(.+?)' if isk(sg[0]) else re.escape(sg) for sg in segs)+'$'
    m=re.match(pat, rd)
    if not m: return None
    out=[]; gi=0
    for sg in segs:
        if isk(sg[0]): gi+=1; out.append([sg, m.group(gi)])
        else: out.append(sg)
    return out
